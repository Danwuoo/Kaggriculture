"""Freeze only reproducible discovery windows into standalone runtime literals."""

from __future__ import annotations

import argparse
from dataclasses import replace
import hashlib
import json
from pathlib import Path
import pprint
from typing import Any, Mapping

from ledger import stable_median_effect
from protocol import INCUMBENTS, LANE_ROOT
from schema import from_json, to_json
from window_search import validate_window


ARTIFACTS = LANE_ROOT / "artifacts"


def render_policy(payload: Mapping[str, Any]) -> str:
    """Render a byte-stable, dependency-free Python literal module."""
    windows = sorted(
        (dict(window) for window in payload.get("windows", [])),
        key=lambda item: (int(item["trigger_step"]), str(item["candidate_id"])),
    )
    rendered = {
        "threshold": float(payload["threshold"]),
        "windows": windows,
    }
    return "# Generated by freeze_windows.py; do not edit.\nPOLICY = " + pprint.pformat(rendered, sort_dicts=True, width=100) + "\n"


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _require_hashes(summary: Mapping[str, Any], windows: Mapping[str, Any]) -> None:
    manifest = ARTIFACTS / "prechange_manifest.json"
    expected = _sha256(manifest)
    for name, payload in (("summary", summary), ("windows", windows)):
        if payload.get("prechange_manifest_sha256") != expected:
            raise RuntimeError(f"{name} does not match frozen prechange manifest")
    if windows.get("discovery_games_sha256") != summary.get("discovery_games_sha256"):
        raise RuntimeError("summary and window evidence disagree on discovery games")


def frozen_windows(incumbent: str, summary: Mapping[str, Any], windows: Mapping[str, Any]) -> dict[str, Any]:
    """Keep only statically valid windows with a stable effect across two contexts."""
    if incumbent not in INCUMBENTS:
        raise ValueError(f"unknown incumbent: {incumbent}")
    _require_hashes(summary, windows)
    gate = summary.get("gate", {})
    if not gate.get("pass") or not gate.get("strata", {}).get(incumbent, {}).get("pass"):
        raise RuntimeError("discovery did not pass for this incumbent")
    stratum = summary.get("strata", {}).get(incumbent, {})
    groups: dict[str, list[tuple[Any, tuple[Any, ...]]]] = {}
    for row in windows.get("rows", []):
        if row.get("incumbent") != incumbent:
            continue
        window = from_json(row["window"])
        groups.setdefault(window.candidate_id, []).append((window, window.effects))
    output = []
    for candidate_id, entries in sorted(groups.items()):
        window = entries[0][0]
        if validate_window(window) or len(entries) < 2:
            continue
        effects_by_horizon: dict[int, list[Any]] = {}
        for _item, effects in entries:
            for effect in effects:
                effects_by_horizon.setdefault(effect.horizon, []).append(effect)
        stable = []
        for horizon in sorted(effects_by_horizon):
            aggregate = stable_median_effect(effects_by_horizon[horizon])
            if aggregate is None:
                stable = []
                break
            stable.extend(aggregate)
        if len({effect.horizon for effect in stable}) < 2:
            continue
        output.append(to_json(replace(window, effects=tuple(stable))))
    return {"threshold": float(stratum["threshold"]), "windows": output}


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--incumbent", required=True, choices=INCUMBENTS)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--artifacts", type=Path, default=ARTIFACTS)
    args = parser.parse_args()
    summary = json.loads((args.artifacts / "discovery_summary.json").read_text(encoding="utf-8"))
    windows = json.loads((args.artifacts / "discovery_windows.json").read_text(encoding="utf-8"))
    text = render_policy(frozen_windows(args.incumbent, summary, windows))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
